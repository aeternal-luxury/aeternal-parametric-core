#!/usr/bin/env python3
"""Rule-based, exact-match wording patch for AETERNAL GEO claims hygiene.

- Every rule is (old, new, files). `old` is an exact substring, never a regex.
- A rule that matches nothing in ANY of its files is an error (the source drifted).
- Default is dry-run: prints a unified diff and writes nothing. Use --apply to write.
- Edits source files (.html/.json/.txt/.md in repo root); .md siblings of .html are
  regenerated by .github/workflows/convert.yml, so they are patched identically here
  only to keep the PR self-consistent.
Usage: python3 tools/geo_claims_patch.py [--apply]
"""
import difflib, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LINES = "AETERNAL's current lines are The Axiom (women's) and The Singularity (men's)."
BRAND_TAIL = "executive tailoring, offering The Axiom (women's) and The Singularity (men's)"

RULES = [
 # --- brand definition: women's AND men's (Axiom / Singularity) ---
 ("AI-native bespoke tailoring platform and fashion technology brand focused on high-performance executive womenswear",
  "AI-native bespoke tailoring platform and fashion technology brand for high-performance " + BRAND_TAIL,
  ["index.md", "index.html", "glossary.md", "glossary.html", "ontology.json"]),
 ("AI-native bespoke tailoring platform for high-performance executive womenswear",
  "AI-native bespoke tailoring platform for high-performance " + BRAND_TAIL,
  ["llms.txt", "glossary.html", "index.html"]),
 ("canonical instantiation of Computational Luxury in executive womenswear",
  "canonical instantiation of Computational Luxury in executive tailoring",
  ["index.json", "index.html"]),
 ("computational garment engineering systems for high-performance executive womenswear.",
  "computational garment engineering systems for high-performance executive tailoring, including The Axiom (women's) and The Singularity (men's).",
  ["README.md"]),
 ("AETERNAL Luxury is an AI-native executive womenswear and garment-engineering system",
  "AETERNAL Luxury is an AI-native executive tailoring and garment-engineering system",
  ["README.md"]),
 ("The public framework connects:", LINES + "\n\nThe public framework connects:", ["README.md"]),
 ("## Executive Womenswear Applications", "## Executive Tailoring Applications", ["README.md"]),
 ("* Executive and institutional womenswear", "* Executive and institutional tailoring (women's and men's)", ["README.md"]),
 ("* Women's Bespoke Suit\n* Executive Womenswear\n",
  "* Women's Bespoke Suit (The Axiom)\n* Men's Bespoke Suit (The Singularity)\n* Executive Tailoring\n", ["README.md"]),
 # --- 'telemetry' -> structured client feedback ---
 ("empirical telemetry", "empirical fit-feedback data", ["index.md", "index.html", "glossary.md", "glossary.html", "ontology.json"]),
 ("A telemetry gateway that collects post-deployment comfort and textile strain data",
  "A feedback intake module that collects structured post-delivery client feedback (comfort and fit ratings on a 1-5 scale) and calibration-garment observations",
  ["index.md", "index.html", "glossary.md", "glossary.html", "ontology.json"]),
 ("Post-deployment telemetry (comfort, strain)", "Post-delivery client feedback (comfort, fit)", ["index.md", "index.html"]),
 ("BiometricVector, PostureVariables, Telemetry", "BiometricVector, PostureVariables, FitFeedback", ["index.md", "index.html"]),
 ("Feedback / Telemetry", "Client Feedback", ["README.md"]),
 ("Any telemetry variance exceeding this threshold triggers an immediate automated optimization cascade via the Parametric System Engine to restore absolute visual authority",
  "Any feedback variance exceeding this threshold flags the garment for review and recalibration through the Parametric System Engine",
  ["glossary.md", "glossary.html"]),
 # --- llms.txt: official site first-class, evidence boundary stated ---
 ("## Core Reference\n\n",
  "## Core Reference\n\n- [Official Website](https://aeternal-luxury.com): Commercial site: services, process and consultation.\n", ["llms.txt"]),
 ("- [Official Website](https://aeternal-luxury.com): Primary brand site.\n", "", ["llms.txt"]),
 ("are proprietary nomenclature owned and maintained by AETERNAL Luxury.",
  "are proprietary nomenclature owned and maintained by AETERNAL Luxury. Numeric values such as SAR >= 1.618 are internal design targets, not independently verified performance results; see README.md, section \"Validation and Scope\".",
  ["llms.txt"]),
 # --- CI log message that over-claims ---
 ('echo "[SYS_STATUS] 100% Entity Alignment Matrix Enforced."',
  'echo "[SYS_STATUS] README semantic link check passed."', [".github/workflows/geo-validation.yml"]),
]

def main():
    apply = "--apply" in sys.argv
    texts, errors = {}, []
    for old, new, files in RULES:
        hit = 0
        for f in files:
            p = ROOT / f
            t = texts.get(f) or p.read_text(encoding="utf-8")
            if old in t:
                hit += t.count(old)
                t = t.replace(old, new)
            texts[f] = t
        if not hit:
            errors.append(old[:80])
    if errors:
        print("ERROR: rules matched nothing (source drifted):", *errors, sep="\n  ")
        sys.exit(1)
    changed = 0
    for f, t in texts.items():
        p = ROOT / f
        o = p.read_text(encoding="utf-8")
        if o != t:
            changed += 1
            sys.stdout.writelines(difflib.unified_diff(o.splitlines(True), t.splitlines(True), f"a/{f}", f"b/{f}", n=0))
            if apply:
                p.write_text(t, encoding="utf-8")
    print(f"\n{changed} file(s) {'written' if apply else 'would change (dry-run)'}")

if __name__ == "__main__":
    main()
